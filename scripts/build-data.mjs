import { readFile, writeFile } from "node:fs/promises";
import { validateRecords } from "../src/validation.js";
import { distanceMiles, coverageCenter } from "../src/locations.js";
const root = new URL("../", import.meta.url),
  records = [];
for (const name of ["dtla", "west", "north", "central"]) {
  try {
    records.push(
      ...JSON.parse(
        await readFile(new URL(`research/${name}.json`, root), "utf8"),
      ),
    );
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}
const coordinates = JSON.parse(
  await readFile(new URL("research/coordinates.json", root), "utf8"),
);
const approvals = JSON.parse(
  await readFile(new URL("research/coordinate-approvals.json", root), "utf8"),
);
const adjustments = JSON.parse(
  await readFile(new URL("research/record-adjustments.json", root), "utf8"),
);
const reviewed = records.map((record) => ({
  ...record,
  hours: record.hours.map((window) => ({
    ...window,
    ...(adjustments[record.id]?.restriction &&
    window.restriction === "conditional"
      ? { restriction: adjustments[record.id].restriction }
      : {}),
  })),
  menu: record.menu.map((item) => ({
    ...item,
    ...(adjustments[record.id]?.itemPairs?.[item.id]
      ? { pairWithIds: adjustments[record.id].itemPairs[item.id] }
      : {}),
    ...(adjustments[record.id]?.itemDays?.[item.id]
      ? { days: adjustments[record.id].itemDays[item.id] }
      : {}),
  })),
  coordinates:
    record.coordinates ||
    approvals[record.address] ||
    coordinates[record.address] ||
    null,
}));
const outside = reviewed.filter(
  (record) =>
    record.coordinates &&
    distanceMiles(coverageCenter, record.coordinates) > 25,
);
const included = reviewed.filter((record) => !outside.includes(record));
const errors = validateRecords(included);
if (errors.length) throw new Error(errors.join("\n"));
const metadata = {
  collectedOn: "2026-10-19",
  target: 100,
  total: included.length,
  located: included.filter((r) => r.coordinates).length,
  primaryHours: included.filter((r) =>
    r.hours.some((w) => w.status === "primary"),
  ).length,
  primaryFoodAndDrink: included.filter((r) =>
    ["food", "drink"].every((kind) =>
      r.menu.some(
        (item) =>
          item.kind === kind &&
          item.status === "primary" &&
          Number.isSafeInteger(item.priceCents),
      ),
    ),
  ).length,
  outsideRadius: outside.map((r) => r.id),
};
await writeFile(
  new URL("src/data.js", root),
  `// Generated by scripts/build-data.mjs from reviewed research records.\nexport const restaurants = ${JSON.stringify(included, null, 2)};\nexport const dataMetadata = ${JSON.stringify(metadata, null, 2)};\n`,
);
